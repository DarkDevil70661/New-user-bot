def get_hindi_reply(user_text: str) -> str:
    """
    हिंदी टेक्स्ट इनपुट प्रोसेस करके अधिकतम 1-2 इमोजी के साथ उत्तर देता है।
    विशेष कमांड के बिना गाना या म्यूजिक नहीं बजाएगा।
    """
    clean_text = user_text.strip().lower()
    
    # पहले चेक करेगा यूजर गाना या म्यूजिक मांग रहा है या नहीं
    for music_key, music_response in MUSIC_RESPONSES.items():
        if music_key in clean_text:
            return music_response
            
    # 100 विशिष्ट रिस्पॉन्स चेक करेगा
    for key, response in HINDI_RESPONSES.items():
        if key in clean_text:
            return response
            
    # मैच न होने पर डिफ़ॉल्ट हिंदी रिस्पॉन्स देगा
    return HINDI_RESPONSES["डिफ़ॉल्ट"]


# सिरोको प्लगइन के रूप में रजिस्टर करने का फंक्शन
def load_plugin():
    return {
        "name": "HindiPlugin",
        "version": "1.0",
        "handler": get_hindi_reply
    }
