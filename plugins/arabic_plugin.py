def get_arabic_reply(user_text: str) -> str:
    """
    يقوم بمعالجة نص المستخدم باللغة العربية والرد بإيموجي مناسبة.
    لا يرد بالموسيقى إلا إذا طلبت خصيصاً.
    """
    clean_text = user_text.strip().lower()
    
    # أولاً: التحقق مما إذا كان المستخدم يطلب تشغيل الموسيقى
    for music_key, music_response in MUSIC_RESPONSES.items():
        if music_key in clean_text:
            return music_response
            
    # ثانياً: البحث في الـ 100 رد المتاحة
    for key, response in ARABIC_RESPONSES.items():
        if key in clean_text:
            return response
            
    # إذا لم يتطابق شيء، يتم إرجاع الرد الافتراضي
    return ARABIC_RESPONSES["افتراضي"]


# دالة تسجيل البلاغين في سيروكو
def load_plugin():
    return {
        "name": "ArabicPlugin",
        "version": "1.0",
        "handler": get_arabic_reply
    }
